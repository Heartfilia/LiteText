use serde::{Deserialize, Serialize};

/// 支持的界面语言。新增语言时：扩展此枚举 + LANGS 列表，并为 `Strings` 增加一份翻译表。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    #[serde(rename = "zh-CN")]
    ZhCn,
    #[serde(rename = "en")]
    En,
}

impl Lang {
    /// 语言在界面上的自称（始终用该语言本身显示）。
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::ZhCn => "简体中文",
            Lang::En => "English",
        }
    }

    pub const ALL: [Lang; 2] = [Lang::ZhCn, Lang::En];

    fn strings(self) -> &'static Strings {
        match self {
            Lang::ZhCn => &ZH_CN,
            Lang::En => &EN,
        }
    }
}

